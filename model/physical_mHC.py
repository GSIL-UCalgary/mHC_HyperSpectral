def get_class_boundary(gt_map, class_id):
    """
    gt_map: (H, W)
    returns: binary boundary mask (H, W)
    """
    class_mask = (gt_map == class_id)
    boundary = find_boundaries(class_mask, mode="outer")
    return boundary

import matplotlib.pyplot as plt
import numpy as np

def plot_all_Hres_boundaries_single_figure(
    H_res, gt_map, class_means,
    stream_names=None,
    class_names=None,
    cmap="viridis",
    save_path=None,
    percentile=(5, 95)   # robust scaling
):
    """
    Plot all H_res(i,j) in ONE figure with class boundary overlays.
    Each subplot uses its own color scale derived from its data.
    """

    L, N, _ = H_res.shape
    H, W = gt_map.shape
    assert L == H * W, "H_res must match spatial resolution (L = H*W)"

    fig, axes = plt.subplots(N, N, figsize=(3*N, 3*N))

    for i in range(N):
        for j in range(N):
            ax = axes[i, j]

            # spatial map
            H_map = H_res[:, i, j].reshape(H, W)

            # per-map color scaling
            vmin, vmax = np.percentile(H_map, percentile)

            # dominant class (GT is 1-based)
            class_idx = np.nanargmax(class_means[i, j])
            boundary = get_class_boundary(gt_map, class_idx)

            ax.imshow(H_map, cmap=cmap, vmin=vmin, vmax=vmax)
            ax.contour(boundary, colors="red", linewidths=0.8)

            if stream_names:
                ax.set_title(f"{stream_names[i]} → {stream_names[j]}", fontsize=9)
            else:
                ax.set_title(f"H({i},{j})", fontsize=9)

