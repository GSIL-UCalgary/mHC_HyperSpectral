def compute_class_means(H_res, gt, num_classes, ignore_label=None):
    """
    H_res: (L, N, N)
    gt:    (L,)
    returns: class_means of shape (N, N, num_classes)
    """
    L, N, _ = H_res.shape
    class_means = np.zeros((N, N, num_classes))

    for c in range(num_classes):
        if ignore_label is not None:
            mask = (gt == c)
        else:
            mask = (gt == c)

        if mask.sum() == 0:
            class_means[:, :, c] = np.nan
            continue    
        class_means[:, :, c] = H_res[mask].mean(axis=0)

    return class_means

